#!/usr/bin/env python3
"""Crop/resize licensed source photos into the storefront's image directories
and write the asset manifest (public/images/manifest.json + ASSET_MANIFEST.md).

Usage: python3 scripts/process_images.py <source_dir>
<source_dir> holds the original downloads named <unsplash-photo-id>.jpg
(fetched from https://images.unsplash.com/photo-<id>?w=1600).
"""
import json, os, sys
from PIL import Image, ImageOps

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SPEC = json.load(open(os.path.join(ROOT, 'scripts', 'images.json')))
SRC = sys.argv[1]
SIZES = {'4:5': (960, 1200), '3:4': (1050, 1400), '16:9': (1920, 1080), '4:3': (1600, 1200), '2:3': (1000, 1500)}

def bg_color(im):
    w, h = im.size
    px = [im.getpixel(p) for p in [(4, 4), (w - 5, 4), (4, h - 5), (w - 5, h - 5)]]
    return tuple(sum(c[i] for c in px) // 4 for i in range(3))

def render(e):
    im = Image.open(os.path.join(SRC, e['src'] + '.jpg')).convert('RGB')
    im = ImageOps.exif_transpose(im)
    W, H = im.size
    tw, th = SIZES[e.get('ratio', '4:5')]
    r = tw / th
    zoom = e.get('zoom', 1.0)
    if e.get('mode') == 'pad':
        # fit whole photo inside the ratio, pad with sampled background
        canvas = Image.new('RGB', (tw, th), tuple(e.get('bg', bg_color(im))))
        s = min(tw / W, th / H) * zoom
        rim = im.resize((int(W * s), int(H * s)), Image.LANCZOS)
        canvas.paste(rim, ((tw - rim.width) // 2, int((th - rim.height) * e.get('fy', 0.5))))
        out = canvas
    else:
        if W / H > r:
            ch, cw = H, H * r
        else:
            cw, ch = W, W / r
        cw, ch = cw / zoom, ch / zoom
        cx, cy = e.get('fx', 0.5) * W, e.get('fy', 0.5) * H
        x0 = min(max(cx - cw / 2, 0), W - cw)
        y0 = min(max(cy - ch / 2, 0), H - ch)
        out = im.crop((int(x0), int(y0), int(x0 + cw), int(y0 + ch))).resize((tw, th), Image.LANCZOS)
    if e.get('gray'):
        out = ImageOps.grayscale(out).convert('RGB')
    dst = os.path.join(ROOT, 'public', 'images', e['file'])
    out.save(dst, 'JPEG', quality=84, optimize=True, progressive=True)
    return out.size

manifest = []
for e in SPEC:
    size = render(e)
    manifest.append({
        'file': '/images/' + e['file'],
        'usedFor': e['use'],
        'subject': e['subject'],
        'source': 'Unsplash',
        'unsplashPhotoId': 'photo-' + e['src'],
        'originalImage': 'https://images.unsplash.com/photo-' + e['src'],
        'license': 'Unsplash License (https://unsplash.com/license) - free commercial use, no attribution required',
        'processing': ('padded' if e.get('mode') == 'pad' else 'cropped') + f" to {e.get('ratio', '4:5')} ({size[0]}x{size[1]})" + (', greyscale' if e.get('gray') else ''),
    })
json.dump(manifest, open(os.path.join(ROOT, 'public', 'images', 'manifest.json'), 'w'), indent=2)
with open(os.path.join(ROOT, 'ASSET_MANIFEST.md'), 'w') as f:
    f.write('# Asset manifest\n\nEvery image in `public/images/` is a real photograph from Unsplash, used under the\n[Unsplash License](https://unsplash.com/license) (free for commercial and non-commercial use, no permission or\nattribution needed). Only `images.unsplash.com/photo-*` assets were used (no Unsplash+ premium images).\nCandidate photos showing prominent third-party brand logos (e.g. sportswear or eyewear marks) were rejected.\nA few kept photos contain small incidental text on garments (the black beanie/pink beanie woven tab, the\nlilac tee chest print, the circle print tee, the graphic tee and the tee worn under the puffer jacket);\nreplace those if the prototype is ever shown publicly. Each photo was checked by eye to show the garment named\nin its product title. Generated by `scripts/process_images.py`\nfrom `scripts/images.json`; machine-readable copy: `public/images/manifest.json`.\n\n')
    f.write('| File | Used for | Photo shows | Original (Unsplash CDN) |\n|---|---|---|---|\n')
    for m in manifest:
        f.write(f"| `{m['file']}` | {m['usedFor']} | {m['subject']} | [{m['unsplashPhotoId']}]({m['originalImage']}) |\n")
print(len(manifest), 'images written')
